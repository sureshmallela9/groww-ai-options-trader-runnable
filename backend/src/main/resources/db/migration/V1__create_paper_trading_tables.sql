CREATE TABLE TRADING_SETTINGS (
    SETTING_ID VARCHAR2(20) NOT NULL,
    CAPITAL_LIMIT NUMBER(18,2) NOT NULL,
    RISK_PER_TRADE_PCT NUMBER(5,2) NOT NULL,
    DAILY_LOSS_PCT NUMBER(5,2) NOT NULL,
    MAX_ENTRY_ORDERS NUMBER(10,0) NOT NULL,
    STOP_PROFITABLE_TRADES NUMBER(10,0) NOT NULL,
    CONSTRAINT PK_TRADING_SETTINGS PRIMARY KEY (SETTING_ID)
);

