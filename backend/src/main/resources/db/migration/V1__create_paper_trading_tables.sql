CREATE TABLE PAPER_TRADES (
    TRADE_ID VARCHAR2(40) NOT NULL,
    SYMBOL VARCHAR2(64) NOT NULL,
    OPTION_TYPE VARCHAR2(8) NOT NULL,
    QUANTITY NUMBER(10,0) NOT NULL,
    ENTRY_PREMIUM NUMBER(18,2) NOT NULL,
    EXIT_PREMIUM NUMBER(18,2),
    GROSS_PNL NUMBER(18,2),
    CHARGES NUMBER(18,2),
    NET_PNL NUMBER(18,2),
    STATUS VARCHAR2(16) NOT NULL,
    ENTRY_REASON VARCHAR2(1000) NOT NULL,
    EXIT_REASON VARCHAR2(1000),
    ENTRY_TIME TIMESTAMP WITH TIME ZONE NOT NULL,
    EXIT_TIME TIMESTAMP WITH TIME ZONE,
    EVIDENCE_JSON CLOB NOT NULL,
    TIMELINE_JSON CLOB NOT NULL,
    CONSTRAINT PK_PAPER_TRADES PRIMARY KEY (TRADE_ID)
);

CREATE INDEX IDX_PAPER_TRADES_ENTRY_TIME ON PAPER_TRADES (ENTRY_TIME);