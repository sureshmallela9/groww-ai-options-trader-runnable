CREATE TABLE PAPER_TRADES (
    TRADE_ID VARCHAR(40) NOT NULL,
    SYMBOL VARCHAR(64) NOT NULL,
    OPTION_TYPE VARCHAR(8) NOT NULL,
    QUANTITY INTEGER NOT NULL,
    ENTRY_PREMIUM NUMERIC(18,2) NOT NULL,
    EXIT_PREMIUM NUMERIC(18,2),
    GROSS_PNL NUMERIC(18,2),
    CHARGES NUMERIC(18,2),
    NET_PNL NUMERIC(18,2),
    STATUS VARCHAR(16) NOT NULL,
    ENTRY_REASON VARCHAR(1000) NOT NULL,
    EXIT_REASON VARCHAR(1000),
    ENTRY_TIME TIMESTAMP WITH TIME ZONE NOT NULL,
    EXIT_TIME TIMESTAMP WITH TIME ZONE,
    EVIDENCE_JSON TEXT NOT NULL,
    TIMELINE_JSON TEXT NOT NULL,
    CONSTRAINT PK_PAPER_TRADES PRIMARY KEY (TRADE_ID)
);

CREATE INDEX IDX_PAPER_TRADES_ENTRY_TIME ON PAPER_TRADES (ENTRY_TIME);