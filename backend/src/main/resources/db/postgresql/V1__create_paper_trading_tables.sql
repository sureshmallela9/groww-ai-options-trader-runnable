CREATE TABLE TRADING_SETTINGS (
    SETTING_ID VARCHAR(20) NOT NULL,
    CAPITAL_LIMIT NUMERIC(18,2) NOT NULL,
    RISK_PER_TRADE_PCT NUMERIC(5,2) NOT NULL,
    DAILY_LOSS_PCT NUMERIC(5,2) NOT NULL,
    MAX_ENTRY_ORDERS INTEGER NOT NULL,
    STOP_PROFITABLE_TRADES INTEGER NOT NULL,
    CONSTRAINT PK_TRADING_SETTINGS PRIMARY KEY (SETTING_ID)
);

