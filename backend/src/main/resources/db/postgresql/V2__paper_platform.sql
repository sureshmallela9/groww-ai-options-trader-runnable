CREATE TABLE PAPER_INTENTS (
    INTENT_ID VARCHAR(40) PRIMARY KEY,
    DECISION_ID VARCHAR(100) NOT NULL UNIQUE,
    REQUEST_KEY VARCHAR(100) NOT NULL UNIQUE,
    REQUEST_HASH VARCHAR(64) NOT NULL,
    STATE VARCHAR(32) NOT NULL,
    SYMBOL VARCHAR(32) NOT NULL,
    SESSION_DATE VARCHAR(10) NOT NULL,
    PAYLOAD_JSON TEXT NOT NULL,
    UPDATED_AT VARCHAR(40) NOT NULL
);
CREATE INDEX IX_PAPER_INTENTS_SESSION ON PAPER_INTENTS(SESSION_DATE,STATE);
CREATE TABLE PLATFORM_OUTBOX (
    EVENT_ID VARCHAR(100) PRIMARY KEY,
    INTENT_ID VARCHAR(40) NOT NULL REFERENCES PAPER_INTENTS(INTENT_ID),
    PAYLOAD_JSON TEXT NOT NULL,
    STATUS VARCHAR(16) NOT NULL CHECK (STATUS IN ('PENDING','DELIVERED')),
    ATTEMPTS INTEGER DEFAULT 0 NOT NULL,
    NEXT_ATTEMPT_AT VARCHAR(40) NOT NULL,
    CREATED_AT VARCHAR(40) NOT NULL
);
CREATE INDEX IX_PLATFORM_OUTBOX_PENDING ON PLATFORM_OUTBOX(STATUS,NEXT_ATTEMPT_AT);
CREATE TABLE PLATFORM_INBOX (
    EVENT_ID VARCHAR(100) PRIMARY KEY REFERENCES PLATFORM_OUTBOX(EVENT_ID),
    INTENT_ID VARCHAR(40) NOT NULL REFERENCES PAPER_INTENTS(INTENT_ID),
    RESPONSE_JSON TEXT NOT NULL,
    RECEIVED_AT VARCHAR(40) NOT NULL
);
CREATE TABLE PLATFORM_AUDIT (
    AUDIT_ID VARCHAR(40) PRIMARY KEY,
    EVENT_TYPE VARCHAR(80) NOT NULL,
    PAYLOAD_JSON TEXT NOT NULL,
    CREATED_AT VARCHAR(40) NOT NULL
);
CREATE INDEX IX_PLATFORM_AUDIT_TIME ON PLATFORM_AUDIT(CREATED_AT);
